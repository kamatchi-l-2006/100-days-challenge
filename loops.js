console.log("LOOP TYPES");
// for loop
console.log("FOR LOOP");
for(let i=0;i<=10;i++){
    console.log("for: ",i);
}
// while loop
console.log("WHILE LOOP");
let i=1;
while(i<=10){
    console.log("While: ",i);
    i++;
}
// Do while Loop
console.log("DO WHILE LOOP");
let j=1;
do{
    console.log("Do while: ",j);
    j++;
}
while(j<=10);
// For of Loop
console.log("FOR..OF LOOP");
for(const element of arr){
    console.log("For of: ",element);
}
